#!/usr/bin/env node
// Сборка промпта страницы из сценария — перенос боевых правил из continuation/q*.txt.

const STYLES = {
  kino: {
    label: 'Кино-комикс',
    text: 'цветной современный кинематографичный комикс, уверенный чёрный контур, насыщенные цвета, мягкие тени, атмосферный свет'
  },
  anime: {
    label: 'Аниме (бета)',
    text: 'аниме-стиль, чистая уверенная линия, выразительные глаза, сочные цвета, мягкое свечение'
  },
  noir: {
    label: 'Нуар ч/б (бета)',
    text: 'чёрно-белый нуар-комикс, глубокие чёрные тени, контрастная штриховка, драматичный свет'
  },
  retro: {
    label: 'Ретро 80-х (бета)',
    text: 'ретро-комикс восьмидесятых, точечный растр, яркие плоские цвета, винтажная печать'
  }
};

const COLS_WORD = { 1: 'одну колонку', 2: 'две колонки', 3: 'все три колонки' };
const TYPE_WORD = { speech: 'пузырь', thought: 'пузырь-мысль с облачками', shout: 'крик-пузырь' };

function panelText(p) {
  const parts = [p.scene.trim().replace(/\s+/g, ' ')];
  if (p.caption) parts.push(`белая плашка «${p.caption}»`);
  (p.bubbles || []).forEach(b => {
    // Имя героя нельзя ставить рядом с цитатой — модель лепит его внутрь пузыря
    // (баг «Ника Мой зонт!»). Сначала цитата и запрет лишних слов, привязка — после.
    const tail = b.who ? `хвост ко рту говорящего героя (${b.who})` : 'хвост ко рту говорящего';
    parts.push(`${TYPE_WORD[b.type] || 'пузырь'}: внутри написано ровно «${b.text}» и больше НИ ОДНОГО слова, имён в пузыре нет; ${tail}`);
  });
  return parts.join('; ');
}

function heroesBlock(heroes) {
  return heroes.map(h => `${h.name} — ${h.desc}`).join('; ');
}

// pageNo/total — человеческая нумерация; page — объект страницы сценария;
// heroes — [{name, desc}]; styleKey — из STYLES.
function buildPagePrompt({ page, pageNo, total, heroes, styleKey, title, wish }) {
  const style = (STYLES[styleKey] || STYLES.kino).text;
  const rows = page.rows.map((r, i) => {
    const cells = r.panels.map(p => `кадр на ${COLS_WORD[p.cols] || 'одну колонку'}: ${panelText(p)}`);
    return `РЯД ${i + 1} — ${cells.join('; рядом ')}.`;
  }).join(' ');

  return `Страница ${pageNo} из ${total} комикса «${title}», вертикальная, сетка три на три, свой узор слияния кадров, плавное действие. ${rows} ` +
    `Рамки кадров — тонкие чёрные линии; поля между кадрами и по краям страницы узкие, примерно полтора процента ширины, ровные и одинаковые; ` +
    `все кадры строго прямоугольные, рисунок не выходит за рамки, кадры сопоставимых размеров без резких перепадов масштаба. ` +
    `Анатомия аккуратная: кисти рук прорисованы правильно, ровно по пять пальцев, конечности правильной формы, лица без искажений. ` +
    `Весь леттеринг — единый аккуратный округлый комикс-шрифт, как ручной леттеринг классических комиксов, одинаковый на всех страницах этой истории; ` +
    `текст на русском, чистый, крупный, без ошибок; аккуратные скруглённые пузыри, хвост ко рту говорящего, первый говорящий выше и левее. ` +
    `Рисовка: ${style}. ГЕРОИ точно как на референсах, лица узнаваемые во всех кадрах: ${heroesBlock(heroes)}. Одежда героев одинаковая на всех страницах, без логотипов известных брендов и супергероев.` +
    (wish ? ` ОСОБОЕ ПОЖЕЛАНИЕ ЗАКАЗЧИКА к этой странице, выполнить обязательно: ${wish}.` : '');
}

function buildHeroSheetPrompt({ name, desc, styleKey, fromPhoto = true }) {
  const style = (STYLES[styleKey] || STYLES.kino).text;
  // Урок из практики: лист из фото всегда просить идеализировать, иначе модель
  // переносит усталый взгляд и неровности кожи с исходника.
  const face = fromPhoto
    ? 'лицо точно как на фото-референсах, но идеализировано: чистая гладкая кожа, бодрый уверенный взгляд, лёгкая полуулыбка; '
    : 'лицо выразительное и запоминающееся, лёгкая полуулыбка; ';
  return `Лист персонажа комикса: ${name} — ${desc}; в полный рост на белом фоне, поза спокойная и уверенная, ` +
    face +
    `анатомия аккуратная, кисти рук прорисованы, ровно по пять пальцев; одежда обычная современная, без логотипов; ` +
    `рисовка: ${style}; без текста и надписей.`;
}

function buildCoverPrompt({ title, logline, heroes, styleKey }) {
  const style = (STYLES[styleKey] || STYLES.kino).text;
  return `Обложка комикса, вертикальная, один цельный кадр без сетки. Сверху крупно название «${title}» — большой выразительный округлый комикс-леттеринг, без ошибок; других надписей на обложке НЕТ. ` +
    `Герои крупным планом в эффектной постановке, передающей суть истории: ${logline}. Атмосферный фон по мотивам истории, глубина, драматичный свет, обложка как у настоящего выпуска. ` +
    `Тонкая чёрная рамка по краю, узкое белое поле. Анатомия аккуратная: кисти рук прорисованы, ровно по пять пальцев, лица без искажений. ` +
    `Рисовка: ${style}. ГЕРОИ точно как на референсах, лица узнаваемые: ${heroesBlock(heroes)}. Одежда как на референсах, без логотипов.`;
}

module.exports = { STYLES, buildPagePrompt, buildHeroSheetPrompt, buildCoverPrompt };
