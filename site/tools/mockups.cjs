#!/usr/bin/env node
// Пять макетов дизайна студии от нейросети — владелец выберет направление.
// Каждый готовый макет сразу уходит в телеграм. nohup, лог: tools/mockups.log.

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const SITE = path.resolve(__dirname, '..');
const ENGINE = path.resolve(SITE, '..', 'neo3-visual');
const TG = path.resolve(SITE, '..', 'bot', 'tg.js');

fs.writeFileSync(path.join(__dirname, 'mockups.pid'), String(process.pid));
const log = m => console.log(`${new Date().toISOString()} ${m}`);

// Одинаковое содержимое экрана во всех вариантах — сравнение честное.
const CONTENT = 'На экране: сверху логотип NEARX COMICS; большой заголовок «ТВОЯ ИСТОРИЯ — ТВОЙ КОМИКС»; ' +
  'полоса шагов «1 Герои, 2 История, 3 Сценарий, 4 Комикс»; зона загрузки с двумя квадратами фото и плюсом; ' +
  'большая кнопка «Собрать свой комикс»; внизу горизонтальная полоса из четырёх миниатюр страниц комикса. ' +
  'Все надписи на русском, читаемые, без ошибок. ';

const BASE = 'Реалистичный макет экрана мобильного веб-приложения, вертикальный, весь экран целиком без рамки телефона, ' +
  'профессиональный продуктовый UI-дизайн высокого уровня, аккуратная сетка, чистая современная типографика. ';

const VARIANTS = [
  ['Тёмная студия', 'тёмная тема: глубокий графитово-чёрный фон, аккуратные тёмные карточки с тонкими светлыми обводками, один смелый красный акцент, крупный геометричный заголовочный шрифт, атмосфера дорогой дизайн-студии'],
  ['Комикс-бумага', 'светлая тема: интерфейс свёрстан как страница комикса — каждый блок это кадр в чёткой чёрной рамке с белыми канавками между блоками, заголовок как леттеринг комикса, жёлтые плашки-подписи, кнопка как выносная плашка звука, лёгкий точечный растр на фоне'],
  ['Неоновый вечер', 'тёмно-синяя тема: фон — вечерний город под дождём с неоном, полупрозрачные стеклянные карточки с размытием, неоновые розово-голубые акценты и светящиеся края кнопок, атмосфера как в романтическом комиксе про город'],
  ['Издательский светлый', 'светлая тема: кремовая бумага, строгая чёрная типографика с засечками в заголовке, красные тонкие акценты, много воздуха, тонкие линейки-разделители, вид дорогого печатного журнала о комиксах'],
  ['Плакат', 'контрастная тема: чисто белый фон, огромные чёрные цифры шагов как на плакате, жирная брутальная типографика, красные крупные кнопки, толстые чёрные разделители, дерзкий постерный стиль']
];

function vis(args, timeoutMin = 8) {
  return execFileSync('node', [path.join(ENGINE, 'bin', 'vis.js'), ...args],
    { cwd: ENGINE, stdio: 'pipe', timeout: timeoutMin * 60 * 1000 }).toString();
}

(async () => {
  let ok = 0;
  for (let i = 0; i < VARIANTS.length; i++) {
    const [name, styleText] = VARIANTS[i];
    let file = null;
    for (let attempt = 1; attempt <= 2 && !file; attempt++) {
      try {
        const out = vis(['crea', BASE + CONTENT + 'Направление дизайна: ' + styleText,
          '--models', 'gpt-image-2-text-to-image', '--format', '9:16', '--resolution', '2K']);
        const m = out.match(/Папка:\s*(\S.*)/);
        if (m) {
          const dir = m[1].trim();
          const f = fs.readdirSync(dir).filter(x => x.endsWith('.jpg'))[0];
          if (f) file = path.join(dir, f);
        }
      } catch (e) { log(`макет ${i + 1} попытка ${attempt}: ${String(e.message).slice(0, 150)}`); }
    }
    if (file) {
      try {
        execFileSync('node', [TG, 'send', file, `Макет ${i + 1} из 5 — «${name}»`], { stdio: 'pipe', timeout: 120000 });
        ok++; log(`макет ${i + 1} (${name}) отправлен`);
      } catch (e) { log(`макет ${i + 1} отправка: ${e.message}`); }
    } else log(`макет ${i + 1} (${name}) не вышел`);
  }
  try {
    execFileSync('node', [TG, 'text', `Готово ${ok} из 5 макетов. Какой берём за основу? Ответь цифрой — перекрашу сайт в это направление.`],
      { stdio: 'pipe', timeout: 60000 });
  } catch {}
  try { vis(['reconcile'], 2); } catch {}
  log(`итог: ${ok}/5`);
})();
